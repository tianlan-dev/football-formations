for (const formation of FORMATIONS) {
  if (formation.slots.length !== 11) {
    throw new Error(`${formation.id} has ${formation.slots.length} slots`);
  }
  const ids = formation.slots.map((slot) => slot.pos);
  if (new Set(ids).size !== 11) {
    throw new Error(`${formation.id} repeats a position`);
  }
}

const used = new Set(FORMATIONS.flatMap((formation) => formation.slots.map((slot) => slot.pos)));
for (const id of POS_ORDER) {
  if (!used.has(id)) throw new Error(`unused position ${id}`);
}

export function formationsUsing(pos: PosId): Formation[] {
  return FORMATIONS.filter((formation) => formation.slots.some((slot) => slot.pos === pos));
}

export function slotsByLine(slots: Slot[]) {
  return LINE_ORDER.map((line) => ({
    line,
    slots: slots
      .map((slot, index) => ({ slot, index }))
      .filter(({ slot }) => POSITIONS[slot.pos].line === line)
      .sort((a, b) => a.slot.x - b.slot.x),
  })).filter((group) => group.slots.length > 0);
}
